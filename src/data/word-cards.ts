/**
 * Word games (Hot Seat and Explain It): our own word cards, written for this
 * app. Each card is one word to guess and the words you can't say while
 * describing it. Every level (A1 to C2) has its own cards, so the words a
 * class gets are of a similar difficulty.
 *
 * Each line is written as "word: banned, banned, banned, banned".
 */
import type { Level } from '@/data/questions';

export type WordCard = {
  word: string;
  /** Words the describers (or the explainer) can't say. */
  banned: string[];
  level: Level;
};

function cards(level: Level, lines: string[]): WordCard[] {
  return lines.map((line) => {
    const [word, rest] = line.split(':');
    return { level, word: word.trim(), banned: rest.split(',').map((w) => w.trim()) };
  });
}

/** The cards for one level (all levels when none match). */
export function cardsForLevel(all: readonly WordCard[], level: Level): WordCard[] {
  const atLevel = all.filter((c) => c.level === level);
  return atLevel.length > 0 ? atLevel : [...all];
}

